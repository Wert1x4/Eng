def extra_glosses():
    gloss = {}
    for line in RAW.splitlines():
        line = line.strip()
        if not line:
            continue
        en, ru, uk = line.split("|")
        gloss[en.strip().casefold()] = (ru.strip(), uk.strip())
    return gloss
